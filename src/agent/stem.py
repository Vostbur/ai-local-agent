"""Грубый стеммер для русского: префикс 5 символов."""

from __future__ import annotations


def stem(token: str) -> str:
    """Свести словоформу к стему (префикс 5 символов).

    Сводит «установить» и «установка» к «устан», «документы» и
    «документ» к «докум». Короткие слова (≤5 символов: «16», «гб»,
    «озу») не трогаются — для них важна точность.

    Это эвристика, не полноценная морфология. Для лексического поиска
    (BM25, `find_match`) достаточно; для семантики — эмбеддинги.
    """
    if len(token) <= 5:
        return token
    return token[:5]